"""What size a picture wants on a made prop (docs/PROPGEN.md §15): its own pictures (the slots its paint names), every
part a picture can be wrapped over, as the page shows them. The rule: the texture's pixels a millimetre there, twice
over (sharp in a close-up, or on a texture twice the size), rounded up to 16 and never under 64. Bigger is fine: a
picture is scaled down. `python tools/propgen.py pictures` writes them all into docs/PROPGEN_PICTURES.md."""

import json
import math
import os

CUT = ("logo", "flourish", "stamp", "text")


def px_per_mm(meta, island):
    isl = meta["islands"][island]
    px = (meta.get("materials") or {}).get(isl["mat"], {}).get("px", 1024)
    return (isl["rect"][2] - isl["rect"][0]) * px / max(isl["mm"][0], 1e-6)


def wants(meta, island, w_mm, h_mm):
    s = px_per_mm(meta, island)
    r = lambda v: max(64, int(math.ceil(v * s * 2 / 16)) * 16)
    return r(w_mm), r(h_mm)


def rows(meta):
    """(what, kind, about, mm, px, notes) for each of the prop's own pictures, then each part."""
    out = []
    for sl in meta.get("slots") or []:
        if sl["island"] not in meta["islands"]:
            continue
        isl = meta["islands"][sl["island"]]
        w, h = sl["box"][2], sl["box"][3]
        if sl.get("relief"):
            notes = ["pressed in or raised, no colour: where it's opaque, or dark on white"]
        elif sl["kind"] == "pattern":
            notes = ["this size, or a smaller tile seamless all round: it repeats (`fit: tile`)"]
        elif sl["kind"] == "flourish" and w >= 4 * h:
            notes = ["a strip seamless at its ends: it repeats along (`fit: tile`), PNG, transparent round it"]
        else:
            notes = ["PNG, transparent round it" if sl["kind"] in CUT else "PNG or JPEG"]
            if isl.get("wrap") and w >= isl["mm"][0] * 0.95:
                notes.append("seamless left to right")
        out.append((f"`pictures.{sl['id']}`", sl["kind"], sl.get("about", ""), (w, h), wants(meta, sl["island"], w, h), ", ".join(notes)))
    for name, isl in meta["islands"].items():
        w, h = isl["mm"]
        notes = ["the whole part (a decal with `fit`), PNG or JPEG"]
        if isl.get("wrap"):
            notes.append("goes round: seamless left to right")
        out.append((f"part `{name}`", isl["mat"], "", (w, h), wants(meta, name, w, h), ", ".join(notes)))
    return out


def write_doc(out_dir, path, names=None):
    """Every made prop's table into one Markdown file, by family."""
    metas = []
    for n in sorted(names or os.listdir(out_dir)):
        mp = os.path.join(out_dir, n, "meta.json")
        if os.path.exists(mp):
            metas.append(json.load(open(mp, encoding="utf-8")))
    lines = ["# Pictures for the prop generator's props: what size each wants", "",
             "Generated by `python tools/propgen.py pictures` from the made props (Saved/Props/*/meta.json); docs/PROPGEN.md §15 says",
             "how pictures, flourishes and smudges go on. The size is for the recipe's texture (its `tex`), twice its pixels a",
             "millimetre there: sharp in a close-up, and on a texture twice the size. Bigger is fine (it's scaled down); smaller goes",
             "soft. A smudge or a decal wants its own width in mm at the same density (the page shows each one's). A key with `*`",
             "swaps every picture it matches (`pictures.*.logo`: every one named logo).", ""]
    fam = None
    for m in sorted(metas, key=lambda m: (m["family"], m["name"])):
        if m["family"] != fam:
            fam = m["family"]
            lines += [f"## {fam}", ""]
        own = sum(1 for _ in (m.get("slots") or []))
        lines += [f"### {m['name']}" + (f": {m['spec'].get('label')}" if m.get("spec", {}).get("label") else ""), "",
                  f"{own} picture{'s' if own != 1 else ''} of its own." if own else "No picture of its own: wrap a part, or add decals and smudges.", "",
                  "| what | kind | about | on the prop (mm) | wants (px) | notes |", "|---|---|---|---|---|---|"]
        for what, kind, about, (w, h), (pw, ph), notes in rows(m):
            lines.append(f"| {what} | {kind} | {about} | {w:.0f} × {h:.0f} | {pw} × {ph} | {notes} |")
        lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return len(metas)

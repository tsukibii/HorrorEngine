"""A cast member's body, designed in the desk, as a MetaHuman Creator script (docs/METAHUMAN_ROUTE.md §3).

    python tools/metahuman.py --game G <cast id> [--out FILE] [--no-rig] [--no-export]

Writes Saved/Story/<Game>/metahuman_<id>.py for the editor's Python (UE 5.8 or later, the MetaHuman Character plugin
and Python scripting enabled): run it through UnrealClaude (`unreal_execute_script`) or
`UnrealEditor-Cmd.exe <project> -ExecutePythonScript=<file>`. It creates (or opens) the MetaHuman Character, sets
the parametric body's constraints from the desk's measures, commits the skin tone, requests the auto-rig, assembles,
and exports the rigged body as FBX for the desk (`previs_body`).

UNTESTED against a real editor (this kit was written without one): the subsystem calls follow the 5.8 docs; the
lines marked VERIFY are the ones to check against Engine/Plugins/MetaHuman/MetaHumanCharacter/Content/Python/examples
on the first run (SETUP S12), after which the MEASURES table below carries the real constraint names.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "Content" / "Python"))
from storykit import storylib as L  # noqa: E402

# the desk's measures (cm, the Shape page's `measure`) -> candidate MetaHuman body constraint names, matched by a
# case-insensitive substring at run time; the script prints every constraint name it finds if one has no match
MEASURES = {
    "height": ["Height"],
    "shoulders": ["Shoulder", "ShoulderWidth", "Shoulders"],
    "chest": ["Chest", "Bust"],
    "waist": ["Waist"],
    "belly": ["Belly", "Stomach", "Abdomen"],
    "hips": ["Hip", "Hips"],
    "thighs": ["Thigh"],
    "arms": ["UpperArm", "Arm"],
}

SCRIPT = r'''# generated by tools/metahuman.py for cast member {cid!r} of {game!r}: the desk's body as a MetaHuman
import unreal

CID, GAME = {cid!r}, {game!r}
MEASURES_CM = {measures}          # the desk's measures (cm): name -> value
CANDIDATES = {candidates}         # desk name -> constraint name candidates (substring match)
SKIN = {skin}                     # {{"u": .., "v": ..}} on Creator's skin tone map, or a hex colour, or None
ASSET_DIR = "/Game/Games/%s/Characters" % GAME
ASSET = {asset!r} or ("%s/MH_%s" % (ASSET_DIR, CID))
RIG, EXPORT = {rig}, {export}
FBX_OUT = r"{fbx_out}"

sub = unreal.get_editor_subsystem(unreal.MetaHumanCharacterEditorSubsystem)
tools = unreal.AssetToolsHelpers.get_asset_tools()
eal = unreal.EditorAssetLibrary

# 1. the character: open it if it exists, else a new MetaHuman Character asset
if eal.does_asset_exist(ASSET):
    char = eal.load_asset(ASSET)
else:
    char = tools.create_asset(ASSET.rsplit("/", 1)[1], ASSET.rsplit("/", 1)[0], unreal.MetaHumanCharacter, unreal.MetaHumanCharacterFactoryNew())   # VERIFY: the factory's name (examples/create_character.py)
    unreal.log("made %s" % ASSET)
if not sub.try_add_object_to_edit(char):          # VERIFY: snake case of TryAddObjectToEdit
    raise RuntimeError("the subsystem would not take %s for editing" % ASSET)

try:
    # 2. the parametric body: match the desk's measures to the constraints by name, set, commit
    cons = sub.get_body_constraints(char, True)   # True: ranges scaled by height (VERIFY the flag's position)
    names = [str(c.name) for c in cons]           # VERIFY: the struct's name field (print(dir(cons[0])))
    def find(desk):
        for cand in CANDIDATES[desk]:
            for k, n in enumerate(names):
                if cand.lower() in n.lower():
                    return k
        return -1
    missing = []
    for desk, cm in MEASURES_CM.items():
        k = find(desk)
        if k < 0:
            missing.append(desk); continue
        c = cons[k]
        c.is_active = True                        # VERIFY: the "pinned" flag's name
        c.target_measurement = float(cm)          # VERIFY: the value field (cm? the examples say)
        cons[k] = c                               # the list yields copies: write it back by index
    if missing:
        unreal.log_warning("no constraint matched %s; the constraints are: %s" % (missing, names))
    sub.set_body_constraints(char, cons)
    sub.commit_body_state(char)
    unreal.log("body committed from the desk's measures: %s" % dict((k, v) for k, v in MEASURES_CM.items() if k not in missing))

    # 3. the skin tone
    if SKIN:
        skin = sub.get_skin_settings(char)        # VERIFY: the getter and FMetaHumanCharacterSkinSettings's fields
        if isinstance(SKIN, dict):
            skin.skin.u, skin.skin.v = float(SKIN["u"]), float(SKIN["v"])    # the tone map coordinates
        else:
            unreal.log_warning("skin %s is a hex colour: Creator's tone is a (u, v) on its tone map; pick the nearest and put {\"u\":..,\"v\":..} in cast.skin (VERIFY the mapping on the first run)" % SKIN)
        sub.commit_skin_settings(char, skin)
        unreal.log("skin committed: %s" % SKIN)

    # 4. the rig (the cloud auto-rig) and the assembly
    if RIG:
        sub.request_auto_rigging(char, unreal.MetaHumanCharacterRigType.JOINTS_AND_BLENDSHAPES)    # VERIFY: the call and the enum (examples/autorig.py)
        unreal.log("auto-rig requested; wait for it before assembling")
    params = unreal.MetaHumanCharacterEditorBuildParameters()
    sub.build_meta_human(char, params)            # BuildMetaHuman: the assembled Blueprint beside the character
    unreal.log("assembled %s" % ASSET)
finally:
    sub.remove_object_to_edit(char)               # VERIFY: the matching remove call
unreal.EditorAssetLibrary.save_asset(ASSET)

# 5. the rigged body as FBX for the desk (Content/Studio/Bodies/<id>.fbx -> previs_body)
if EXPORT:
    body = None
    for a in eal.list_assets(ASSET_DIR, recursive=True):
        if a.endswith("_Body") or "/Body/" in a:  # VERIFY: where the assembled body skeletal mesh lands
            body = eal.load_asset(a); break
    if body is None:
        unreal.log_warning("no body skeletal mesh found under %s: export it by hand (Asset Actions > Export)" % ASSET_DIR)
    else:
        task = unreal.AssetExportTask()
        task.object, task.filename, task.automated, task.replace_identical, task.prompt = body, FBX_OUT, True, True, False
        opts = unreal.FbxExportOption(); opts.collision = False; opts.level_of_detail = False   # LOD 0 only: the desk reads one mesh
        task.options = opts
        unreal.Exporter.run_asset_export_task(task)
        unreal.log("exported %s" % FBX_OUT)
'''


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--game", required=True)
    ap.add_argument("cid", help="the cast member's id")
    ap.add_argument("--out")
    ap.add_argument("--no-rig", action="store_true")
    ap.add_argument("--no-export", action="store_true")
    a = ap.parse_args(argv)
    story, _ = L.load(a.game)
    cast = story.get("cast", {})
    if a.cid not in cast:
        sys.exit(f"{a.cid!r} isn't in {a.game}'s cast: {', '.join(cast)}")
    c = cast[a.cid]
    measures = dict(c.get("measures") or {})
    if "height" not in measures and c.get("height"):
        measures["height"] = round(float(c["height"]) * 100, 1)
    if not measures:
        print(f"{a.cid} has no measures: open the Shape page, shape the body and Save to story (it writes `measures`)", file=sys.stderr)
    out = Path(a.out) if a.out else ROOT / "Saved" / "Story" / a.game / f"metahuman_{a.cid}.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    fbx = ROOT / "Content" / "Studio" / "Bodies" / f"{a.cid}.fbx"
    out.write_text(SCRIPT.format(cid=a.cid, game=a.game, measures=json.dumps(measures), candidates=json.dumps(MEASURES),
                                 skin=json.dumps(c.get("skin")), asset=c.get("metahuman") or "", rig=not a.no_rig,
                                 export=not a.no_export, fbx_out=str(fbx)), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(measures)} measures, skin {c.get('skin')!r}); run it in the editor (UnrealClaude: unreal_execute_script)")
    print("METAHUMAN ok")


if __name__ == "__main__":
    main()
